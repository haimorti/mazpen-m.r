WORD_RE = re.compile(r'[א-ת]+')
POINTS = re.compile(r'[֑-ׇ]')


def unpoint(s):
    return POINTS.sub('', unicodedata.normalize('NFD', s))


def point(line):
    """The line as the engine should read it. Unknown words are left alone."""
    out, missing = line, []
    for src, spoken, _ in PHRASES:
        out = out.replace(src, spoken)

    # walk the pointed-so-far text word by word, skipping anything already pointed
    parts, i = [], 0
    for m in re.finditer(r'[א-ת֑-ׇ]+', out):
        parts.append(out[i:m.start()])
        w = m.group(0)
        if POINTS.search(w):
            parts.append(w)
        elif w in WORDS:
            parts.append(WORDS[w])
        else:
            missing.append(w)
            parts.append(w)
        i = m.end()
    parts.append(out[i:])
    return ''.join(parts), missing


def as_written(line):
    """The plain line after the deliberate substitutions -- what point() must strip back to."""
    for src, _, written in PHRASES:
        line = line.replace(src, written)
    return line


def build():
    out, missing, broken = {}, set(), []
    for name in SOURCES:
        path = os.path.join(ROOT, 'video', name)
        for row in json.load(open(path, encoding='utf-8')):
            plain = row['text']
            spoken, miss = point(plain)
            missing.update(miss)
            if unpoint(spoken) != as_written(plain):
                broken.append((name, row['i'], plain, spoken))
            out[plain] = spoken
    return out, sorted(missing), broken


